import type { Theme } from '../theme.ts'
import { banner, type Emitter, type Output, owned } from './index.ts'

export const kitty: Emitter = {
  id: 'kitty',

  emit(theme: Theme): Output[] {
    const colors = [
      ...banner(theme),
      `background ${theme.background}`,
      `foreground ${theme.foreground}`,
      `cursor ${theme.cursor}`,
      `cursor_text_color ${theme.background}`,
      `selection_background ${theme.selectionBackground}`,
      `selection_foreground ${theme.foreground}`,
      ...theme.ansi.map((c, i) => `color${i} ${c}`),
      '',
    ].join('\n')

    return [{ path: `kitty/themes/${owned(theme.name)}.conf`, content: colors }]
  },
}

export interface KittyWatcher {
  themes: string
  backgrounds: string
}

export function kittyWatcher(m: KittyWatcher): string {
  return [
    '# Generated by ttheme — rewritten on every add, remove and default; do not edit.',
    'import os',
    '',
    `THEMES = ${JSON.stringify(m.themes)}`,
    `BACKGROUNDS = ${JSON.stringify(m.backgrounds)}`,
    'PLACES = {',
    "    'top-left': 'top-left', 'top-center': 'top', 'top-right': 'top-right',",
    "    'center-left': 'left', 'center': 'center', 'center-center': 'center', 'center-right': 'right',",
    "    'bottom-left': 'bottom-left', 'bottom-center': 'bottom', 'bottom-right': 'bottom-right',",
    '}',
    '',
    'shown = {}',
    'faded = {}',
    'worn = {}',
    '',
    '',
    'def locate(path):',
    "    if path.startswith('~/'):",
    '        return os.path.expanduser(path)',
    '    return path if os.path.isabs(path) else os.path.join(BACKGROUNDS, path)',
    '',
    '',
    'def read(path, into):',
    '    try:',
    "        with open(path, encoding='utf-8') as f:",
    '            lines = f.read().splitlines()',
    '    except OSError:',
    '        return False',
    '    for line in lines:',
    "        key, sep, value = line.partition('=')",
    '        key, value = key.strip(), value.strip()',
    "        if not sep or not key or key.startswith('#'):",
    '            continue',
    "        if key == 'config-file':",
    "            read(locate(value.lstrip('?')), into)",
    '        else:',
    '            into[key] = value',
    '    return True',
    '',
    '',
    'def logo(palette):',
    '    c = {}',
    "    if not palette or not read(os.path.join(BACKGROUNDS, palette.replace('@', '--', 1) + '.conf'), c):",
    '        return None',
    "    image = c.get('background-image', '')",
    '    try:',
    "        opacity = min(float(c.get('background-image-opacity', '1')), 1.0)",
    '    except ValueError:',
    '        opacity = 1.0',
    '    if not image or opacity <= 0:',
    '        return None',
    "    return locate(image), PLACES.get(c.get('background-image-position', 'center'), 'center'), opacity",
    '',
    '',
    'def fade(path, opacity):',
    "    key = f'{path}#{opacity}'",
    '    if key not in faded:',
    '        from kitty.fast_data_types import load_png_data, png_from_32bit_rgba_data',
    "        with open(path, 'rb') as f:",
    '            rgba, width, height = load_png_data(f.read())',
    '        data = bytearray(rgba)',
    '        data[3::4] = data[3::4].translate(bytes(round(a * opacity) for a in range(256)))',
    '        if len(faded) > 8:',
    '            faded.clear()',
    '        faded[key] = png_from_32bit_rgba_data(bytes(data), width, height)',
    '    return key, faded[key]',
    '',
    '',
    'def show(window):',
    "    want = logo(window.user_vars.get('ttheme_shown') or '')",
    '    if window.id in shown and shown[window.id] == want:',
    '        return',
    '    shown[window.id] = want',
    '    try:',
    '        if want is None:',
    "            window.set_logo('')",
    '        elif want[2] < 1:',
    '            key, png = fade(want[0], want[2])',
    '            window.set_logo(key, want[1], 1, png)',
    '        else:',
    '            window.set_logo(want[0], want[1], 1)',
    '    except Exception:',
    '        shown.pop(window.id, None)',
    '',
    '',
    'def theme(palette):',
    "    path = os.path.join(THEMES, 'ttheme-' + palette.replace('@', '--', 1) + '.conf')",
    '    if not palette or not os.path.exists(path):',
    '        return None',
    '    from kitty.colors import parse_colors',
    '    return parse_colors([path])',
    '',
    '',
    'def wear(palette):',
    "    colors = theme(palette) if worn.get('startup') != palette else None",
    '    if colors is None:',
    '        return',
    '    from kitty.colors import patch_colors',
    '    patch_colors(colors[0], colors[1], True, ())',
    "    worn['startup'] = palette",
    '',
    '',
    'def rewear(boss):',
    '    from kitty.colors import patch_colors',
    '    for window in tuple(boss.all_windows):',
    "        colors = theme(window.user_vars.get('ttheme_worn') or '')",
    '        if colors is not None:',
    '            patch_colors(colors[0], colors[1], False, (window,))',
    '',
    '',
    'def on_load(boss, data):',
    "    if getattr(boss, 'ttheme_rewears', False):",
    '        return',
    '    load = boss.load_config_file',
    '',
    '    def reload(*args, **kwargs):',
    '        load(*args, **kwargs)',
    "        worn.pop('startup', None)",
    '        rewear(boss)',
    '',
    '    boss.load_config_file = reload',
    '    boss.ttheme_rewears = True',
    '',
    '',
    'def on_set_user_var(boss, window, data):',
    "    if data['key'] == 'ttheme_shown':",
    '        show(window)',
    "    elif data['key'] == 'ttheme_startup':",
    "        wear(data['value'] or '')",
    '',
    '',
    'def on_focus_change(boss, window, data):',
    "    if data['focused']:",
    '        show(window)',
    '',
    '',
    'def on_close(boss, window, data):',
    '    shown.pop(window.id, None)',
    '',
  ].join('\n')
}
