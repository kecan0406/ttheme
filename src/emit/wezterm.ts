import type { Theme } from '../theme.ts'
import { type Emitter, type Output, owned } from './index.ts'

const list = (colors: readonly string[]) => `[${colors.map((c) => `"${c}"`).join(', ')}]`

export const wezterm: Emitter = {
  id: 'wezterm',
  limits: 'OSC repaints per pane, pictures show per window',

  emit(theme: Theme): Output[] {
    const colors = [
      '[metadata]',
      `name = "${owned(theme.name)}"`,
      `origin_url = "${theme.ansiSource}"`,
      '',
      '[colors]',
      `foreground = "${theme.foreground}"`,
      `background = "${theme.background}"`,
      `cursor_bg = "${theme.cursor}"`,
      `cursor_border = "${theme.cursor}"`,
      `cursor_fg = "${theme.background}"`,
      `selection_bg = "${theme.selectionBackground}"`,
      `selection_fg = "${theme.foreground}"`,
      '',
      `ansi = ${list(theme.ansi.slice(0, 8))}`,
      `brights = ${list(theme.ansi.slice(8, 16))}`,
      '',
    ].join('\n')

    return [{ path: `wezterm/colors/${owned(theme.name)}.toml`, content: colors }]
  },
}

export interface WeztermModule {
  path: string
  colors: string
  backgrounds: string
  startup?: string
  palettes: Theme[]
}

const lua = (value: string) => JSON.stringify(value)

export function weztermModule(m: WeztermModule): string {
  return [
    '-- Generated by ttheme — rewritten on every add, remove and default; do not edit.',
    "local wezterm = require 'wezterm'",
    '',
    `local MODULE = ${lua(m.path)}`,
    `local COLORS = ${lua(m.colors)}`,
    `local BACKGROUNDS = ${lua(m.backgrounds)}`,
    `local STARTUP = ${m.startup ? lua(owned(m.startup)) : 'nil'}`,
    'local PALETTES = {',
    ...m.palettes.map((t) => `  [${lua(t.name)}] = ${lua(t.background)},`),
    '}',
    '',
    "local X = { left = 'Left', center = 'Center', right = 'Right' }",
    "local Y = { top = 'Top', center = 'Middle', bottom = 'Bottom' }",
    "local SIZE = { cover = 'Cover', contain = 'Contain', stretch = '100%' }",
    '',
    'local function locate(path)',
    "  if path:sub(1, 2) == '~/' then",
    "    return os.getenv('HOME') .. path:sub(2)",
    "  elseif path:sub(1, 1) == '/' or path:match('^%a:[/\\\\]') then",
    '    return path',
    '  end',
    "  return BACKGROUNDS .. '/' .. path",
    'end',
    '',
    'local function read(path, into)',
    "  local f = io.open(path, 'r')",
    '  if not f then',
    '    return false',
    '  end',
    '  for line in f:lines() do',
    "    local key, value = line:match('^%s*([%w%-]+)%s*=%s*(.-)%s*$')",
    "    if key == 'config-file' then",
    "      read(locate((value:gsub('^%?', ''))), into)",
    '    elseif key then',
    '      into[key] = value',
    '    end',
    '  end',
    '  f:close()',
    '  return true',
    'end',
    '',
    'local function layers(palette)',
    '  local color = PALETTES[palette]',
    '  local c = {}',
    "  if not color or not read(BACKGROUNDS .. '/' .. palette .. '.conf', c) then",
    "    return nil, 'none'",
    '  end',
    "  local image = c['background-image'] or ''",
    "  local opacity = tonumber(c['background-image-opacity'] or '1') or 1",
    "  if image == '' or opacity <= 0 then",
    "    return nil, 'none'",
    '  end',
    "  local fit = c['background-image-fit'] or 'contain'",
    "  local position = c['background-image-position'] or 'center'",
    "  local y, x = position:match('^(%a+)-(%a+)$')",
    "  local rep = c['background-image-repeat'] == 'true' and 'Repeat' or 'NoRepeat'",
    '  return {',
    "    { source = { Color = color }, width = '100%', height = '100%' },",
    '    {',
    '      source = { File = locate(image) },',
    '      opacity = opacity,',
    '      width = SIZE[fit],',
    '      height = SIZE[fit],',
    "      horizontal_align = X[x or 'center'],",
    "      vertical_align = Y[y or 'center'],",
    '      repeat_x = rep,',
    '      repeat_y = rep,',
    '    },',
    "  }, table.concat({ color, image, opacity, fit, position, rep }, '|')",
    'end',
    '',
    'local shown = {}',
    '',
    'local function show(window, pane)',
    '  local want = pane:get_user_vars().ttheme_shown',
    "  if not want or want == '' then",
    '    return',
    '  end',
    '  local background, key = layers(want)',
    '  local id = window:window_id()',
    '  if shown[id] == key then',
    '    return',
    '  end',
    '  shown[id] = key',
    '  local overrides = window:get_config_overrides() or {}',
    '  overrides.background = background',
    '  window:set_config_overrides(overrides)',
    'end',
    '',
    "wezterm.on('user-var-changed', function(window, pane, name)",
    "  if name == 'ttheme_shown' then",
    '    show(window, pane)',
    '  end',
    'end)',
    "wezterm.on('update-status', show)",
    '',
    'return function(config)',
    '  local dirs = config.color_scheme_dirs or {}',
    '  table.insert(dirs, COLORS)',
    '  config.color_scheme_dirs = dirs',
    '  if STARTUP then',
    '    config.color_scheme = STARTUP',
    '  end',
    '  wezterm.add_to_config_reload_watch_list(MODULE)',
    'end',
    '',
  ].join('\n')
}
