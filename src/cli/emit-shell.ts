import pkg from '../../package.json' with { type: 'json' }
import { SITES } from '../core/booru.ts'
import { aboutOf, type Work, workOf, worksFor, worldOrder } from '../core/commons.ts'
import { listed, type PaletteEntry, swatch } from '../core/manifest.ts'
import { marksOf } from '../core/mark.ts'
import type { Mode, Setting } from '../core/mode.ts'
import { SCENES } from '../core/scenes.ts'
import { slugOf } from '../core/theme.ts'
import { configTemplate, SETTING_NAMES } from '../store/wiring.ts'
import { TRAITS } from '../terminals/terminal.ts'
import { HUB_CLOSED, HUB_SWITCH, HUB_TABS, HUB_UPDATE } from '../tui/hub.ts'
import { outdatedLines, STANDING_LINES } from '../tui/notice.ts'
import { PREVIEW_KEYS } from '../tui/preview-keys.ts'
import { painter } from '../tui/style.ts'
import { bannerHead, helpText, VERB_SPECS } from './verbs.ts'

const UNQUOTABLE = /["$`\\]/
const CONTROL = /[\p{Cc}\p{Bidi_Control}]/u

function spoken(tag: string): string {
  return tag.replace(/_\([^)]*\)$/, '').replaceAll('_', ' ')
}

export interface ZshContext {
  startup?: string
  terminals?: readonly string[]
  layer?: Readonly<Record<string, string>>
  tuned?: readonly string[]
  marketplaces?: readonly string[]
  mode?: { worn: Mode; auto: boolean; settings: readonly Setting[] }
}

function byWorkName(a: Work, b: Work): number {
  const x = a.name.toLowerCase()
  const y = b.name.toLowerCase()

  return x < y ? -1 : x > y ? 1 : a.id < b.id ? -1 : a.id > b.id ? 1 : 0
}

export function palettesZsh(palettes: PaletteEntry[], works: readonly Work[], context: ZshContext = {}): string {
  const {
    startup,
    terminals = [],
    layer = {},
    tuned = [],
    marketplaces = [],
    mode = { worn: 'dark', auto: false, settings: ['light', 'dark'] },
  } = context

  const abouts = new Map(palettes.map((p) => [p.name, aboutOf(works, p.subject)]))

  for (const p of palettes) {
    const about = abouts.get(p.name)

    for (const field of [
      p.name,
      p.subject ?? '',
      about?.work.name ?? '',
      about?.work.native ?? '',
      ...(about?.character?.native ?? []),
      p.ansiSource,
    ]) {
      if (UNQUOTABLE.test(field)) {
        throw new Error(`${p.name}: "${field}" contains a character that breaks zsh quoting`)
      }
    }
  }

  const pad = Math.max(0, ...palettes.map((p) => p.name.length))
  const entry = (p: PaletteEntry, value: string) => `  ${p.name.padEnd(pad)} "${value}"`
  const names = (list: PaletteEntry[]) => list.map((p) => p.name).join(' ')
  const rotation = listed(palettes)
  const quote = (text: string) => `'${text.replaceAll("'", "'\\''")}'`
  const verbs = VERB_SPECS.filter((v) => v.section !== 'setup' && !v.hidden)

  const shelved = [
    ...new Set(
      rotation.flatMap((p) => {
        const about = abouts.get(p.name)

        return about ? worksFor(about) : []
      }),
    ),
  ]
    .map((id) => workOf(works, id) ?? { id, name: id, characters: [] })
    .toSorted(byWorkName)

  const workPad = Math.max(0, ...shelved.map((w) => w.id.length))
  const slugs = Map.groupBy(palettes, (p) => slugOf(p.name))
  const slugPad = Math.max(0, ...[...slugs.keys()].map((slug) => slug.length))

  return [
    '# Generated by `mise run build` — do not edit.',
    '# Source of truth: builtin/ and commons/ in the ttheme repo, and the marketplaces this install holds.',
    '',
    `typeset -g TTHEME_VERSION=${pkg.version}`,
    `typeset -g TTHEME_OUTDATED=${quote(outdatedLines(painter(false), '%s', '%s', 'ttheme update').join('\n'))}`,
    `typeset -g TTHEME_OUTDATED_COLOR=${quote(outdatedLines(painter(true), '%s', '%s', 'ttheme update').join('\n'))}`,
    'typeset -gA TTHEME_STANDING=(',
    ...Object.entries(STANDING_LINES).map(([standing, line]) => `  ${standing} ${quote(line)}`),
    ')',
    '',
    '# the palette new tabs open with, which the iTerm2 "ttheme · default" profile shows',
    `typeset -g TTHEME_STARTUP=${startup ?? ''}`,
    '',
    '# the mode TTHEME_PALETTE holds, whether TTHEME_MODE is auto — a tab whose terminal reports the appearance then follows it at its prompt — and the values TTHEME_MODE takes here',
    `typeset -g TTHEME_MODE_WORN=${mode.worn} TTHEME_MODE_AUTO=${mode.auto ? 1 : 0}`,
    `typeset -ga TTHEME_MODE_SETTINGS=(${mode.settings.join(' ')})`,
    '',
    '# the terminals ttheme is wired into: a picture change reaches every one of them, from whichever runs the shell',
    `typeset -ga TTHEME_TERMINALS=(${terminals.join(' ')})`,
    '',
    '# the marketplaces this install holds, by the name `ttheme marketplace remove` and `ttheme update` take: the completion offers them',
    `typeset -ga TTHEME_MARKETPLACES=(${marketplaces.map(quote).join(' ')})`,
    ...(Object.keys(layer).length > 0
      ? [
          '',
          "# what a wired terminal's adapter needs to know of it (src/terminals/)",
          ...Object.entries(layer).map(([key, value]) => `typeset -g ${key}=${quote(value)}`),
        ]
      : []),
    '',
    '# the commands the shell layer knows (src/verbs.ts): help, completion and argument checks read them',
    `typeset -ga TTHEME_VERBS=(${verbs.map((v) => v.name).join(' ')})`,
    `typeset -ga TTHEME_TAB_VERBS=(${verbs
      .filter((v) => v.section === 'tab')
      .map((v) => v.name)
      .join(' ')})`,
    `typeset -ga TTHEME_SHELL_VERBS=(${verbs
      .filter((v) => v.shell)
      .map((v) => v.name)
      .join(' ')})`,
    'typeset -gA TTHEME_VERB_ARGS=(',
    ...verbs.map((v) => `  ${v.name} ${quote(v.args.join(' '))}`),
    ')',
    'typeset -gA TTHEME_VERB_ABOUT=(',
    ...verbs.map((v) => `  ${v.name} ${quote(v.about)}`),
    ')',
    `typeset -g TTHEME_HELP=${quote(helpText(false, true))}`,
    `typeset -g TTHEME_HELP_ALL=${quote(helpText(true, true))}`,
    `typeset -g TTHEME_HELP_HEAD=${quote(bannerHead(painter(true)))}`,
    '',
    '# the screens the bare ttheme switches between (src/hub.ts): the exit status of a screen run by the CLI says where it went',
    `typeset -ga TTHEME_HUB_TABS=(${HUB_TABS.map((tab) => tab.name).join(' ')})`,
    `typeset -ga TTHEME_HUB_TITLES=(${HUB_TABS.map((tab) => tab.title).join(' ')})`,
    `typeset -gi TTHEME_HUB_CLOSED=${HUB_CLOSED} TTHEME_HUB_SWITCH=${HUB_SWITCH} TTHEME_HUB_UPDATE=${HUB_UPDATE}`,
    '',
    "# preview's help (src/tui/preview-keys.ts): where each line shows, its group, its keys and what they do",
    'typeset -ga TTHEME_PREVIEW_KEYS=(',
    ...PREVIEW_KEYS.map((k) => `  ${k.where} ${quote(k.group)} ${quote(k.keys)} ${quote(k.does)}`),
    ')',
    '',
    '# the settings config.zsh holds, handed to the CLI on every call',
    `typeset -ga TTHEME_SETTINGS=(${SETTING_NAMES.join(' ')})`,
    '',
    '# seed for `ttheme config` when no config.zsh exists yet',
    `typeset -g TTHEME_CONFIG_TEMPLATE='${configTemplate().trimEnd().replaceAll("'", "'\\''")}'`,
    '',
    'typeset -gA TTHEME_PALETTE=(',
    ...palettes.map((p) => entry(p, [p.background, p.foreground, p.cursor, p.selection, ...p.ansi].join(' '))),
    ')',
    '',
    '# each palette in its other mode, so a tab still showing a palette in the mode it showed before can be told and repainted',
    'typeset -gA TTHEME_PALETTE_OTHER=(',
    ...palettes.flatMap((p) =>
      p.other
        ? [
            entry(
              p,
              [p.other.background, p.other.foreground, p.other.cursor, p.other.selection, ...p.other.ansi].join(' '),
            ),
          ]
        : [],
    ),
    ')',
    '',
    "# each palette's mark, `>ω` (src/core/mark.ts): its signature colors, each lifted until it reads 3:1 on the palette's background — the hub draws the eye in the second and the mouth in the first",
    'typeset -gA TTHEME_MARK_INKS=(',
    ...palettes.map((p) => entry(p, marksOf(p.background, p.foreground, p.signature).join(' '))),
    ')',
    '',
    "# the palettes whose colors your tuning moves off their marketplace's (tone.json): lists mark them, and preview's panel offers to reset them",
    `typeset -ga TTHEME_TUNED=(${palettes.flatMap((p) => (tuned.includes(p.name) ? [p.name] : [])).join(' ')})`,
    '',
    '# every listed palette by work, each work by name and its characters in the order the commons lists them, the palettes of no work after: new tabs cycle through it and TTHEME_SORT=cast lists it — the fallback palette stays applyable but unlisted',
    `typeset -ga TTHEME_ORDER=(${names(worldOrder(rotation, works, 'cast'))})`,
    '',
    "# the same palettes with each work's characters by name: TTHEME_SORT=abc lists them this way",
    `typeset -ga TTHEME_ABC=(${names(worldOrder(rotation, works, 'abc'))})`,
    '',
    '# what each palette is of: a work, or a work and its character (commons/works/<work>.toml) — a palette of neither is an original, listed under its marketplace',
    'typeset -gA TTHEME_SUBJECT=(',
    ...palettes.flatMap((p) => (p.subject ? [entry(p, p.subject)] : [])),
    ')',
    '',
    "# the other works a palette's character appears in, whose shelves list it too",
    'typeset -gA TTHEME_ALSO=(',
    ...palettes.flatMap((p) => {
      const also = abouts.get(p.name)?.character?.also

      return also ? [entry(p, also.join(' '))] : []
    }),
    ')',
    '',
    '# the works that hold a listed palette, by name, with their names and original-language titles',
    `typeset -ga TTHEME_WORKS=(${shelved.map((w) => w.id).join(' ')})`,
    'typeset -gA TTHEME_WORK_NAME=(',
    ...shelved.map((w) => `  ${w.id.padEnd(workPad)} "${w.name}"`),
    ')',
    'typeset -gA TTHEME_WORK_NATIVE=(',
    ...shelved.flatMap((w) => (w.native ? [`  ${w.id.padEnd(workPad)} "${w.native}"`] : [])),
    ')',
    '',
    '# each palette name as typed without its marketplace, and the palettes it names: `ttheme use rei` takes the one there is, and asks which when there are more',
    'typeset -gA TTHEME_SHORT=(',
    ...[...slugs].map(([slug, list]) => `  ${slug.padEnd(slugPad)} "${names(list)}"`),
    ')',
    '',
    "# the character's names in its original language, |-separated, and as its booru tag spells it: preview searches both",
    'typeset -gA TTHEME_NATIVE_NAMES=(',
    ...palettes.flatMap((p) => {
      const native = abouts.get(p.name)?.character?.native

      return native ? [entry(p, native.join('|'))] : []
    }),
    ')',
    'typeset -gA TTHEME_CHARACTER=(',
    ...palettes.flatMap((p) => {
      const tag = abouts.get(p.name)?.character?.danbooru

      return tag && !UNQUOTABLE.test(tag) ? [entry(p, spoken(tag))] : []
    }),
    ')',
    '',
    '# the example scenes preview draws beside the list (src/scenes.ts), each line as «role»text runs',
    `typeset -ga TTHEME_SCENES=(${SCENES.map((scene) => scene.name).join(' ')})`,
    ...SCENES.flatMap((scene, i) => [
      `typeset -ga TTHEME_SCENE_${i + 1}=(`,
      ...scene.lines.map((line) => `  ${quote(line)}`),
      ')',
    ]),
    '',
    "# each booru's ANSI color, which marks a link to one of its posts",
    `typeset -gA TTHEME_SITE_ANSI=(${SITES.map((site) => `${site.name} ${site.ansi}`).join(' ')})`,
    '',
    '# the terminals that open OSC 8 links (src/terminal.ts)',
    `typeset -ga TTHEME_LINKS=(${Object.entries(TRAITS)
      .flatMap(([terminal, traits]) => (traits.links ? [terminal] : []))
      .join(' ')})`,
    '',
    '# the six colors a list row shows: foreground, the signature, then red and green',
    'typeset -gA TTHEME_SWATCH=(',
    ...palettes.map((p) => entry(p, swatch(p).join(' '))),
    ')',
    '',
    "# where each palette's 16 ANSI colors came from",
    'typeset -gA TTHEME_SRC=(',
    ...palettes.map((p) => entry(p, p.ansiSource)),
    ')',
    '',
  ].join('\n')
}

export function aliasesZsh(aliases: Readonly<Record<string, readonly string[]>>): string {
  const rows = Object.entries(aliases).flatMap(([name, all]) => {
    const names = all.filter((each) => !UNQUOTABLE.test(each) && !CONTROL.test(each) && !each.includes('|'))

    return names.length > 0 && !UNQUOTABLE.test(name) ? [[name, names.join('|')] as const] : []
  })

  const pad = Math.max(0, ...rows.map(([name]) => name.length))

  return [
    "# the character's other names in every language, |-separated, from the aninames index in the cache: preview reads this when it opens and searches them too",
    'typeset -gA TTHEME_ALIASES=(',
    ...rows.map(([name, names]) => `  ${name.padEnd(pad)} "${names}"`),
    ')',
    '',
  ].join('\n')
}
